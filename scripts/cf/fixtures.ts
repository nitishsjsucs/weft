// pnpm cf:fixtures (docs/cloudflare/design.md 4.1 and 9.2 step 1): writes apps/cf/generated/fixtures.ts, the module
// the durable platform reads fixture files from, since a Worker has no file system. It holds the migrations and their
// journal, the mailed and scenario notices and the scripted provider's scenarios, keyed by repo-relative path, in
// sorted order with a content hash, so the output is byte-stable: CI runs `pnpm cf:fixtures && git diff --exit-code
// apps/cf/generated/fixtures.ts`. `--check` exits 1 instead of writing when the module is stale.
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
export const OUT = "apps/cf/generated/fixtures.ts";

/** Directories and the file names taken from each (direct children only). */
export const FIXTURE_DIRS: readonly { dir: string; match: RegExp }[] = [
  { dir: "packages/db/drizzle", match: /^\d{4}_[a-z0-9_]+\.sql$/ },
  { dir: "packages/db/drizzle/meta", match: /^_journal\.json$/ },
  { dir: "packages/sim/src/notices/mailed", match: /^[a-z0-9_]+\.(txt|json)$/ },
  { dir: "packages/sim/fixtures/notices", match: /^[a-z0-9_]+\.txt$/ },
  { dir: "scenarios", match: /^[a-z0-9_.-]+\.json$/ },
];

export function collectFixtures(root = REPO_ROOT): Record<string, string> {
  const files: Record<string, string> = {};
  for (const { dir, match } of FIXTURE_DIRS) {
    const abs = join(root, dir);
    if (!existsSync(abs)) throw new Error(`fixture directory ${dir} is missing`);
    for (const name of readdirSync(abs).filter((n) => match.test(n)).sort()) {
      const bytes = readFileSync(join(abs, name));
      const text = bytes.toString("utf8");
      if (!Buffer.from(text, "utf8").equals(bytes)) throw new Error(`${dir}/${name} is not valid UTF-8; FixtureSource holds text files only`);
      files[relative(root, join(abs, name)).split("\\").join("/")] = text;
    }
  }
  return Object.fromEntries(Object.entries(files).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

export function renderFixtures(files: Record<string, string>): string {
  const hash = createHash("sha256");
  for (const [k, v] of Object.entries(files)) hash.update(k).update("\0").update(v).update("\0");
  const lines = [
    "// Generated by pnpm cf:fixtures (scripts/cf/fixtures.ts) from the repo's fixture files: the migrations and their",
    "// journal, the mailed and scenario notices and the scripted provider's scenarios. Do not edit; CI checks it is fresh.",
    "/* eslint-disable */",
    `export const FIXTURES_HASH = ${JSON.stringify(hash.digest("hex"))};`,
    `export const FIXTURE_COUNT = ${Object.keys(files).length};`,
    "export const FIXTURE_FILES: Readonly<Record<string, string>> = {",
    ...Object.entries(files).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`),
    "};",
    "",
  ];
  return lines.join("\n");
}

function main(argv: string[]): void {
  const out = join(REPO_ROOT, OUT);
  const text = renderFixtures(collectFixtures());
  const current = existsSync(out) ? readFileSync(out, "utf8") : null;
  if (argv.includes("--check")) {
    if (current !== text) {
      console.error(`${OUT} is stale; run pnpm cf:fixtures`);
      process.exit(1);
    }
    console.log(`${OUT} is fresh`);
    return;
  }
  if (current !== text) writeFileSync(out, text);
  const n = (text.match(/^ {2}"/gm) ?? []).length;
  console.log(`${OUT}: ${n} files, ${(Buffer.byteLength(text) / 1024).toFixed(1)} KiB${current === text ? " (unchanged)" : ""}`);
}

if (import.meta.url === `file://${process.argv[1]}`) main(process.argv.slice(2));
