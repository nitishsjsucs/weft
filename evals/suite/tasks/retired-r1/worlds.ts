// runnable for continuity; never edit, and never reuse a name or a world of it in a later split.
// Held-out world mutators for the test split (owner: w4-eval-heldout). Each one is a named, deterministic list of
// steps applied after seedWorld() on the task's frozen clock: SQL statements on the trial database, and memory files
// written into the trial memory repository and committed before the run. Synthetic data only; every inserted row uses
// an id in the 09xx range so it never collides with an id the seed or a run allocates.
//
// The eval runner (w4-eval-suite) resolves a test task's mutator names here first (contract request in
// docs/tracks/w4-eval-heldout.md). Fixers never read this file; they see per-category pass counts only.

export type WorldStep =
  | { readonly sql: string; readonly args?: readonly (string | number | null)[] }
  | { readonly memoryFile: { readonly path: string; readonly content: string } };

export interface TestMutator {
  readonly name: string;
  readonly summary: string;
  readonly steps: readonly WorldStep[];
}

